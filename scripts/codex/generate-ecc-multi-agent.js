#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const {
  extractFrontmatter,
  resolveChineseTranslation,
  sha256,
  TRANSLATION_RESOLUTION_ORDER,
} = require('./load-ecc-agent-translation');

const repoRoot = path.join(__dirname, '..', '..');
const sourceAgentsDir = path.join(repoRoot, 'agents');
const outputDir = path.join(repoRoot, '.codex', 'ecc-multi-agent');
const englishRoleDir = path.join(outputDir, 'agents', 'en');
const chineseRoleDir = path.join(outputDir, 'agents', 'zh-CN');

function ensureDir(dirPath) {
  fs.mkdirSync(dirPath, { recursive: true });
}

function mapModel(model) {
  switch (model) {
    case 'opus':
      return { model: 'gpt-5.6-sol', modelReasoningEffort: 'xhigh' };
    case 'haiku':
      return { model: 'gpt-5.6-luna', modelReasoningEffort: 'high' };
    case 'sonnet':
      return { model: 'gpt-5.6-terra', modelReasoningEffort: 'xhigh' };
    default:
      throw new Error(`Unsupported source model: ${model}`);
  }
}

function inferSandbox(tools) {
  const writeTools = new Set(['Write', 'Edit']);
  return tools.some(tool => writeTools.has(tool)) ? 'workspace-write' : 'read-only';
}

function tomlValue(value) {
  return JSON.stringify(value);
}

function tomlMultiline(value) {
  const normalized = value.replace(/\r\n/g, '\n').trim();
  if (normalized.includes("'''")) {
    throw new Error('developer_instructions contains unsupported triple single quotes');
  }

  return `'''\n${normalized}\n'''`;
}

function renderRoleToml({
  name,
  description,
  sourceFile,
  sourceSha256,
  runtime,
  developerInstructions,
  translationSource,
  translationSourceType,
  translationStatus,
}) {
  const lines = [
    '# Generated by `node scripts/codex/generate-ecc-multi-agent.js`.',
    `# Source: ${sourceFile}`,
    `# Source SHA256: ${sourceSha256}`,
  ];

  if (translationStatus) {
    lines.push(`# Translation status: ${translationStatus}`);
  }

  if (translationSource) {
    const sourceLabel = translationSourceType ? `${translationSource} (${translationSourceType})` : translationSource;
    lines.push(`# Translation source: ${sourceLabel}`);
  }

  lines.push(
    '',
    `name = ${tomlValue(name)}`,
    `description = ${tomlValue(description)}`,
    `model = ${tomlValue(runtime.model)}`,
    `model_reasoning_effort = ${tomlValue(runtime.modelReasoningEffort)}`,
    `sandbox_mode = ${tomlValue(runtime.sandboxMode)}`,
    '',
    `developer_instructions = ${tomlMultiline(developerInstructions)}`,
    '',
  );

  return lines.join('\n');
}

function renderConfigToml({ descriptions }) {
  const sortedNames = Object.keys(descriptions).sort();
  const roleLines = [];

  for (const name of sortedNames) {
    roleLines.push(
      `[agents.${tomlValue(name)}]`,
      `description = ${tomlValue(descriptions[name])}`,
      `config_file = ${tomlValue(`agents/${name}.toml`)}`,
      '',
    );
  }

  return [
    '#:schema https://developers.openai.com/codex/config-schema.json',
    '',
    '# ECC Codex multi-agent role pack',
    '# Merge these tables into `.codex/config.toml` or use this file as a reference.',
    '# Copy the selected role TOMLs into `.codex/agents/` before using these snippets.',
    '# `config_file` paths are intentionally copy-ready for end-user setups.',
    '',
    '[features]',
    'multi_agent = true',
    '',
    '[agents]',
    'max_threads = 6',
    'max_depth = 1',
    '',
    ...roleLines,
  ].join('\n');
}

function renderReadme(manifest) {
  const rows = manifest.agents
    .map(
      agent =>
        `| \`${agent.name}\` | [${agent.sourceFile}](../../${agent.sourceFile}) | \`${agent.model}\` | \`${agent.modelReasoningEffort}\` | \`${agent.sandboxMode}\` | [${agent.translationSource}](../../${agent.translationSource}) (\`${agent.translationSourceType}\`) | \`${agent.translationStatus}\` |`,
    )
    .join('\n');

  return `# ECC Codex Multi-Agent Pack

This directory contains a generated Codex multi-agent role pack derived from the source agents in [\`agents/\`](../../agents).

Official references:
- [Codex multi-agent guide](https://developers.openai.com/codex/multi-agent)
- [Codex config reference](https://developers.openai.com/codex/config-reference)

> Model availability: this pack currently targets the GPT-5.6 preview models
> exposed by the refreshed Codex catalog. Verify access with the filtered
> \`codex debug models\` workflow in the sync skill before installing the pack.

## Files

- \`config.en.toml\` — English role registry for Codex
- \`config.zh-CN.toml\` — Chinese role registry for Codex
- \`agents/en/*.toml\` — English role config files generated from source agent markdown
- \`agents/zh-CN/*.toml\` — Chinese role config files generated from official docs, legacy translation data, or English fallback
- \`manifest.json\` — source hashes, runtime mapping, translation source, and translation status

## Regeneration

Run:

\`\`\`bash
node scripts/codex/generate-ecc-multi-agent.js
\`\`\`

Chinese translation resolution order:

1. [\`docs/zh-CN/agents/*.md\`](../../docs/zh-CN/agents)
2. [\`scripts/codex/ecc-agent-translations.js\`](../../scripts/codex/ecc-agent-translations.js)
3. [\`agents/*.md\`](../../agents) as an English fallback marked with \`translationStatus = "missing"\`

When an official zh-CN agent doc exists, update it there first. Keep the legacy JS map only for agents that do not have an official zh-CN file yet.

## Role Inventory

| Role | Source | Model | Reasoning | Sandbox | Zh-CN Source | Translation |
|------|--------|-------|-----------|---------|--------------|-------------|
${rows}
`;
}

function main() {
  const sourceFiles = fs
    .readdirSync(sourceAgentsDir)
    .filter(file => file.endsWith('.md'))
    .sort();

  const englishDescriptions = {};
  const chineseDescriptions = {};
  const roles = [];
  const manifest = {
    sourceDirectory: 'agents',
    outputDirectory: '.codex/ecc-multi-agent',
    translationSources: TRANSLATION_RESOLUTION_ORDER,
    sourceAgentCount: sourceFiles.length,
    officialDocs: [
      'https://developers.openai.com/codex/multi-agent',
      'https://developers.openai.com/codex/config-reference',
    ],
    agents: [],
  };

  for (const sourceFile of sourceFiles) {
    const sourcePath = path.join(sourceAgentsDir, sourceFile);
    const sourceContent = fs.readFileSync(sourcePath, 'utf8');
    const { frontmatter, body } = extractFrontmatter(sourceContent);
    const runtime = {
      ...mapModel(frontmatter.model),
      sandboxMode: inferSandbox(frontmatter.tools || []),
    };
    const sourceHash = sha256(sourceContent);
    const expectedName = path.basename(sourceFile, '.md');
    const name = frontmatter.name || expectedName;
    if (name !== expectedName) {
      throw new Error(`Agent name must match filename: ${sourceFile}`);
    }
    const translation = resolveChineseTranslation({
      name,
      sourceHash,
      englishDescription: frontmatter.description,
      englishInstructions: body,
      repoRoot,
    });
    englishDescriptions[name] = frontmatter.description;
    chineseDescriptions[name] = translation.description;

    roles.push({
      name,
      english: renderRoleToml({
        name,
        description: frontmatter.description,
        sourceFile: `agents/${sourceFile}`,
        sourceSha256: sourceHash,
        runtime,
        developerInstructions: body,
      }),
      chinese: renderRoleToml({
        name,
        description: translation.description,
        sourceFile: `agents/${sourceFile}`,
        sourceSha256: sourceHash,
        runtime,
        developerInstructions: translation.developerInstructions,
        translationSource: translation.translationSource,
        translationSourceType: translation.translationSourceType,
        translationStatus: translation.translationStatus,
      }),
    });

    manifest.agents.push({
      name,
      sourceFile: `agents/${sourceFile}`,
      sourceSha256: sourceHash,
      description: frontmatter.description,
      descriptionZhCN: translation.description,
      model: runtime.model,
      modelReasoningEffort: runtime.modelReasoningEffort,
      sandboxMode: runtime.sandboxMode,
      translationSource: translation.translationSource,
      translationSourceType: translation.translationSourceType,
      englishConfigFile: `.codex/ecc-multi-agent/agents/en/${name}.toml`,
      chineseConfigFile: `.codex/ecc-multi-agent/agents/zh-CN/${name}.toml`,
      translationStatus: translation.translationStatus,
    });
  }

  fs.rmSync(englishRoleDir, { recursive: true, force: true });
  fs.rmSync(chineseRoleDir, { recursive: true, force: true });
  ensureDir(englishRoleDir);
  ensureDir(chineseRoleDir);
  for (const role of roles) {
    fs.writeFileSync(path.join(englishRoleDir, `${role.name}.toml`), role.english);
    fs.writeFileSync(path.join(chineseRoleDir, `${role.name}.toml`), role.chinese);
  }

  fs.writeFileSync(path.join(outputDir, 'config.en.toml'), renderConfigToml({ descriptions: englishDescriptions }));
  fs.writeFileSync(
    path.join(outputDir, 'config.zh-CN.toml'),
    renderConfigToml({ descriptions: chineseDescriptions }),
  );
  fs.writeFileSync(path.join(outputDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  fs.writeFileSync(path.join(outputDir, 'README.md'), renderReadme(manifest));

  const nonCurrentTranslations = manifest.agents.filter(agent => agent.translationStatus !== 'current');
  if (nonCurrentTranslations.length > 0) {
    console.warn(
      `Generated pack with ${nonCurrentTranslations.length} non-current Chinese translation entries: ${nonCurrentTranslations
        .map(agent => `${agent.name} (${agent.translationStatus})`)
        .join(', ')}`,
    );
  } else {
    console.log(`Generated ECC Codex multi-agent pack for ${manifest.agents.length} roles.`);
  }
}

main();
